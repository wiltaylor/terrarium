//! Turn `harnesses.toml` (the repo root) into `terrarium_core::harnesses`.
//!
//! The file is the one source of truth for the harness pins: the first
//! install into the tools dir uses these versions (`terrariumd harness
//! install`), and the adapters take their `verified` and `tested` values from the consts
//! that this script writes. The build fails when the file is missing, has
//! a harness that Terrarium does not know, or has a `tested` range that
//! does not match its `version`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use serde::Deserialize;

const HARNESSES: [&str; 4] = ["claude", "codex", "copilot", "pi"];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    node: Node,
    harness: BTreeMap<String, Harness>,
    #[serde(default)]
    extension: BTreeMap<String, Extension>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Node {
    image: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Harness {
    package: String,
    version: String,
    tested: String,
    binary: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Extension {
    package: String,
    version: String,
    binary: String,
    #[serde(rename = "for")]
    for_harness: String,
}

fn fail(msg: String) -> ! {
    panic!("harnesses.toml: {msg}");
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let path = manifest.join("../../harnesses.toml");
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| fail(format!("cannot read {}: {e}", path.display())));
    let file: File = toml::from_str(&text).unwrap_or_else(|e| fail(e.to_string()));

    for name in file.harness.keys() {
        if !HARNESSES.contains(&name.as_str()) {
            fail(format!(
                "unknown harness `{name}`; use one of {HARNESSES:?}"
            ));
        }
    }
    for name in HARNESSES {
        let Some(h) = file.harness.get(name) else {
            fail(format!("no [harness.{name}] table"));
        };
        let v = semver::Version::parse(&h.version)
            .unwrap_or_else(|e| fail(format!("{name}: version `{}`: {e}", h.version)));
        let req = semver::VersionReq::parse(&h.tested)
            .unwrap_or_else(|e| fail(format!("{name}: tested `{}`: {e}", h.tested)));
        if !req.matches(&v) {
            fail(format!(
                "{name}: version {} is not in the tested range `{}`",
                h.version, h.tested
            ));
        }
    }
    for (name, e) in &file.extension {
        semver::Version::parse(&e.version)
            .unwrap_or_else(|err| fail(format!("{name}: version `{}`: {err}", e.version)));
        if !HARNESSES.contains(&e.for_harness.as_str()) {
            fail(format!("{name}: unknown harness `{}`", e.for_harness));
        }
    }

    let mut out =
        String::from("// @generated by crates/terrarium-core/build.rs from harnesses.toml.\n\n");
    let _ = writeln!(
        out,
        "/// `[node] image`: the base image of the runtime stage."
    );
    let _ = writeln!(out, "pub const NODE_IMAGE: &str = {:?};\n", file.node.image);
    let _ = writeln!(out, "/// Every `[harness.<name>]` table, in name order.");
    let _ = writeln!(out, "pub const PINS: &[HarnessPin] = &[");
    for name in HARNESSES {
        let h = &file.harness[name];
        let _ = writeln!(
            out,
            "    HarnessPin {{ harness: HarnessId::{}, package: {:?}, version: {:?}, tested: {:?}, binary: {:?} }},",
            variant(name),
            h.package,
            h.version,
            h.tested,
            h.binary
        );
    }
    let _ = writeln!(out, "];\n");
    let _ = writeln!(out, "/// Every `[extension.<name>]` table, in name order.");
    let _ = writeln!(out, "pub const EXTENSIONS: &[ExtensionPin] = &[");
    for (name, e) in &file.extension {
        let _ = writeln!(
            out,
            "    ExtensionPin {{ name: {:?}, package: {:?}, version: {:?}, binary: {:?}, harness: HarnessId::{} }},",
            name,
            e.package,
            e.version,
            e.binary,
            variant(&e.for_harness)
        );
    }
    let _ = writeln!(out, "];");
    for name in HARNESSES {
        let h = &file.harness[name];
        let _ = writeln!(out, "\n/// `[harness.{name}]`.");
        let _ = writeln!(out, "pub mod {name} {{");
        let _ = writeln!(out, "    pub const PACKAGE: &str = {:?};", h.package);
        let _ = writeln!(out, "    pub const VERSION: &str = {:?};", h.version);
        let _ = writeln!(out, "    pub const TESTED: &str = {:?};", h.tested);
        let _ = writeln!(out, "    pub const BINARY: &str = {:?};", h.binary);
        let _ = writeln!(out, "}}");
    }

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("harnesses.rs");
    std::fs::write(&dest, out)
        .unwrap_or_else(|e| fail(format!("cannot write {}: {e}", dest.display())));
}

fn variant(name: &str) -> &'static str {
    match name {
        "claude" => "Claude",
        "codex" => "Codex",
        "copilot" => "Copilot",
        _ => "Pi",
    }
}
